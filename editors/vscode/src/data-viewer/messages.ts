/**
 * Protocol types for the data-viewer postMessage channel.
 *
 * Every message after the initial `webviewReady` handshake carries the
 * panel's monotonic `panelGeneration`. The host bumps it on webview reload
 * and dataset replacement; receivers drop messages from older generations
 * so stale `getRows` / `copy` / `labels` / transform responses cannot leak
 * across those lifecycle boundaries.
 */

import type { Cell } from './wire-format';
import type { ColumnSchema } from './arrow-reader';
import type { ToolbarState } from './toolbar-state';
import type { ProfileUpdate, ValueCounts } from './profile';

export type Layout = {
    /** Per-column pixel widths, keyed by the column's index in the
     *  current schema. Indices are stable for a given schema hash, and
     *  unlike names they don't collide when a data frame has duplicate
     *  column names (e.g. via `data.frame(x = 1, x = 2,
     *  check.names = FALSE)`). */
    columnWidths: Record<number, number>;
    /** Hidden column indices. */
    hiddenColumns: number[];
    /** Pinned column indices, in pin order. Pinned columns are frozen
     *  after the rowname columns (`webview/display-columns.ts`); absent ⇔
     *  none. */
    pinnedColumns?: number[];
};

export type Settings = {
    missingValueStyle: 'foreground' | 'background' | 'none';
    defaultDigits: number;
    persistSort: boolean;
    persistFilters: boolean;
    /** VS Code's UI language (`vscode.env.language`), the explicit locale
     *  for Natural and Locale string sorts. Absent in tests. */
    uiLocale?: string;
};

/** How string keys sort. `natural`: the UI locale's collator with
 *  numeric digit runs (`file_2` before `file_10`), the default.
 *  `locale`: the same collator without numeric runs. `c`: Unicode code
 *  point order, as `sort(method = "radix")` and `dplyr::arrange()`. */
export type StringOrder = 'natural' | 'locale' | 'c';

/** A single sort key. Priority is the position in the SortState.keys array
 *  — index 0 is the primary key, index 1 the secondary, etc. */
export type SortKey = {
    /** Index into ColumnSchema[]. Stable for a given schema hash. */
    columnIndex: number;
    direction: 'asc' | 'desc';
};

export type SortState = {
    keys: SortKey[];
    /** Snapshot of Labels-on at the time the sort was built. Used by the
     *  webview to detect that the Labels toggle has flipped since this
     *  sort was last applied, so a labelled column re-sorts. The host
     *  itself always recomputes the permutation on restore — the
     *  persisted `keys` are the only source of truth for ordering, and
     *  schema-hash equality plus column-name equality is not evidence of
     *  same values. */
    labelsOnWhenSorted: boolean;
    /** String order the sort was built with. Absent ⇔ `natural`. */
    stringOrder?: StringOrder;
};

export const EMPTY_SORT: SortState = {
    keys: [],
    labelsOnWhenSorted: true,
};

/** A single filter predicate. Discriminated by `kind`. Predicate value
 *  storage is in JS-native types — wire serialization is whatever
 *  `JSON.stringify` does, which is fine for everything except `BigInt`
 *  (currently unused since Int64 / Uint64 columns are filtered as
 *  numeric or set predicates, both of which use Number or string keys). */
export type FilterPredicate =
    | { kind: 'isEmpty' }
    | { kind: 'isNotEmpty' }
    | { kind: 'numCompare'; op: '=' | '!=' | '<' | '<=' | '>' | '>='; value: number }
    | {
        kind: 'numBetween'; lo: number; hi: number; inclusive: boolean;
        /** Overrides `inclusive` for the upper bound only, so a histogram
         *  bin `[lo, hi)` (or the closed last bin) filters to exactly the
         *  rows it counts. Absent ⇔ the upper bound follows `inclusive`. */
        upperInclusive?: boolean;
    }
    | { kind: 'numNotBetween'; lo: number; hi: number; inclusive: boolean }
    | { kind: 'setIn'; values: (string | number)[] }
    | { kind: 'setNotIn'; values: (string | number)[] }
    | { kind: 'strCompare'; op: '=' | '!='; value: string; caseSensitive: boolean }
    | { kind: 'strContains'; value: string; caseSensitive: boolean; negate: boolean }
    | { kind: 'strStartsWith'; value: string; caseSensitive: boolean }
    | { kind: 'strEndsWith'; value: string; caseSensitive: boolean }
    | { kind: 'strRegex'; pattern: string; caseSensitive: boolean }
    | { kind: 'dateCompare'; op: '=' | '!=' | '<' | '<=' | '>' | '>='; value: string }
    | { kind: 'dateBetween'; lo: string; hi: string; inclusive: boolean }
    | { kind: 'dateNotBetween'; lo: string; hi: string; inclusive: boolean }
    | { kind: 'bool'; value: boolean };

export type FilterEntry = {
    /** UUID-ish. Stable across edits so a chip-popover Apply updates the
     *  same slot. Generated by the webview on Add; never reused. */
    id: string;
    /** Index into ColumnSchema[]. */
    columnIndex: number;
    predicate: FilterPredicate;
    /** Disabled chips are kept in the strip (greyed) but not applied to
     *  the row index. Lets users A/B a filter without retyping. */
    enabled: boolean;
    /** When true, missing rows pass this entry regardless of predicate.
     *  Semantics: `predicate(x) | is.na(x)`. */
    includeMissing: boolean;
};

export type FilterState = {
    entries: FilterEntry[];
    /** Snapshot of Labels-on at the time the index was computed.
     *  Used by the webview to detect that the Labels toggle has flipped
     *  since this filter was last applied, so labelled columns re-filter.
     *  The host always recomputes the index on restore — `entries` are
     *  the only source of truth for membership, and schema-hash equality
     *  plus column-name equality is not evidence of same values. */
    labelsOnWhenFiltered: boolean;
};

export const EMPTY_FILTER: FilterState = {
    entries: [],
    labelsOnWhenFiltered: true,
};

/** Bin in a numeric column's histogram (computed on demand; see the
 *  `histogram` message). Bins are uniform-width over `[min, max]` of the
 *  present values; NA / NaN rows are excluded from `count`. A column with
 *  no present values serializes to an empty array. */
export type HistogramBin = {
    lo: number;
    hi: number;
    count: number;
};

export type ExtensionToWebview =
    | {
        type: 'init';
        panelGeneration: number;
        nrow: number;
        columns: ColumnSchema[];
        layout: Layout;
        toolbar: ToolbarState;
        settings: Settings;
        /** Shipped dictionaries by column. Sent once per webview and
         *  dataset; omitted when the webview already has them. */
        dictionaries?: Record<number, string[]>;
        /** schemaHash for the active dataset. Echoed back by saveLayout
         *  / saveToolbar / saveSort so the host stores under the hash
         *  that was current when the user toggled, even if a later
         *  replace swapped the dataset before the debounce fired. */
        schemaHash: string;
        /** Sort state restored from persistence, or EMPTY_SORT if none.
         *  Webview reflects this in its header glyphs and toolbar strip
         *  without firing the apply-pulse animation. */
        sort: SortState;
        /** Filter state restored from persistence, or EMPTY_FILTER if
         *  none. Webview reflects this in the chip strip without firing
         *  the apply-pulse animation. */
        filter: FilterState;
        /** Transform generation this paint shows. The webview tags reader
         *  requests with it and acks it with `adopted`. */
        transformGeneration?: number;
    }
    | {
        type: 'rows';
        panelGeneration: number;
        requestId: number;
        viewportGeneration: number;
        start: number;
        end: number;
        rows: Cell[][];
        stale: boolean;
        /** When a sort is active, the original (unsorted) 0-based row
         *  index for each row in this window. Length matches rows.length.
         *  Omitted when no sort is active — the gutter falls back to
         *  `position + 1`. */
        originalRowIndices?: number[];
        /** Echo of the request's `columnRange`, when it sent one. */
        columnRange?: { start: number; end: number };
    }
    | {
        type: 'labels';
        panelGeneration: number;
        requestId: number;
        columnIndex: number;
        labels: Record<number, string>;
    }
    | {
        type: 'replace';
        panelGeneration: number;
        nrow: number;
        columns: ColumnSchema[];
        layout: Layout;
        toolbar: ToolbarState;
        /** See `init`. */
        dictionaries?: Record<number, string[]>;
        schemaHash: string;
        sort: SortState;
        /** Filter state restored from persistence, or EMPTY_FILTER if
         *  none. Webview reflects this in the chip strip without firing
         *  the apply-pulse animation. */
        filter: FilterState;
        /** See `init`. */
        transformGeneration?: number;
    }
    | {
        /** On-demand numeric histogram for a single column, sent in
         *  response to a `getHistogram` request. Histograms are computed
         *  lazily (and cached host-side) the first time a numeric column's
         *  filter popover opens — they are NOT precomputed at init, because
         *  scanning every numeric column up front blocks the grid from
         *  painting on large frames (a multi-second to multi-minute stall).
         *  `bins` is `[]` for a column with no present finite values. */
        type: 'histogram';
        panelGeneration: number;
        requestId: number;
        columnIndex: number;
        bins: HistogramBin[];
    }
    | {
        /** Sent after the extension host has finished building the
         *  permutation for a setSort request. The webview updates its
         *  header glyphs, toolbar sort chips, and gutter renderer, and
         *  clears the "Sorting…" pill. The pulse animation fires only
         *  when `fromPersistence` is false. */
        type: 'sortApplied';
        panelGeneration: number;
        requestId: number;
        sort: SortState;
        fromPersistence: boolean;
        /** True when this is an authoritative rollback after a failed
         *  interactive setSort request. The webview should update display
         *  state but must not persist the rolled-back state as a new user
         *  preference. */
        rollback?: boolean;
        /** Optional failure text carried by a rollback response. */
        error?: string;
        /** Transform generation this announcement shows (see `init`). */
        transformGeneration?: number;
    }
    | {
        /** Lifecycle ping driving the toolbar "Sorting…" progress pill.
         *  `state: 'pending'` shows it; `'idle'` clears it. */
        type: 'sortStatus';
        panelGeneration: number;
        requestId: number;
        state: 'pending' | 'idle';
        /** Set on a `pending` re-post once a Natural or Locale sort has
         *  run past 3 s: the pill offers "Switch to C order". */
        slow?: boolean;
        /** Set when the scan worker restarted and is rebuilding its key
         *  and rank caches. */
        rebuildingKeys?: boolean;
    }
    | {
        /** Filter index has been (re)built. Webview updates the filter
         *  chip strip and gutter renderer, and clears the "Filtering…"
         *  pill. The pulse animation fires only when `fromPersistence`
         *  is false. */
        type: 'filterApplied';
        panelGeneration: number;
        requestId: number;
        filter: FilterState;
        nrowFiltered: number;
        fromPersistence: boolean;
        /** True when this is an authoritative rollback after a failed
         *  interactive setFilters request. The webview should clear pending
         *  intent but must not persist the rolled-back state as a new user
         *  preference. */
        rollback?: boolean;
        /** Optional failure text carried by a rollback response. */
        error?: string;
        /** Transform generation this announcement shows (see `init`). */
        transformGeneration?: number;
    }
    | {
        type: 'filterStatus';
        panelGeneration: number;
        requestId: number;
        state: 'pending' | 'idle';
    }
    | {
        /** Sent before the host reads columns to reapply a saved
         *  sort/filter on open (#519), so the webview can explain the wait
         *  (instead of a bare "Loading…") and offer a skip action.
         *  `restoreId` is a monotonic id identifying this restore so a
         *  `cancelRestore` can be matched to it independently of lifecycle
         *  generation bumps. `sort` / `filter` say which preferences are
         *  being applied (for the wording). */
        type: 'restorePending';
        panelGeneration: number;
        restoreId: number;
        sort: boolean;
        filter: boolean;
    }
    | {
        /** Per-column NA counts from the record-batch headers, posted
         *  progressively after first paint (`done` on the last one).
         *  Indexed by source column; drives the header missing bars. */
        type: 'nullCounts';
        panelGeneration: number;
        counts: number[];
        done: boolean;
    }
    | {
        /** Column profile states (summary band, sidebar), see
         *  `profile-scheduler.ts`. `null` drops a pending column. */
        type: 'profiles';
        panelGeneration: number;
        updates: ProfileUpdate[];
    }
    | {
        /** Reply to `getValueCounts`: the counts, or why they failed. */
        type: 'valueCounts';
        panelGeneration: number;
        requestId: number;
        columnIndex: number;
        result?: ValueCounts;
        error?: string;
    }
    | {
        /** Full value of one cell for the cell-detail popover. */
        type: 'cellDetail';
        panelGeneration: number;
        requestId: number;
        text: string | null;
        /** True when the value exceeded the 64 KiB cap. */
        truncated: boolean;
    }
    | {
        type: 'copyDone';
        panelGeneration: number;
        requestId: number;
        ok: boolean;
        error?: string;
    }
    | {
        /** Reply to `find` / `findStep`: how many rows match and the
         *  match to select. `position` is a display row, `index` its
         *  0-based rank among the matches; both -1 with no match. */
        type: 'findResult';
        panelGeneration: number;
        requestId: number;
        count: number;
        position: number;
        index: number;
        /** The transform generation the positions are in. */
        transformGeneration?: number;
        error?: string;
    }
    | {
        /** Reply to `goToRow`: the display row of R row `rowNumber`, or
         *  -1 when no such row is shown (filtered out or out of range). */
        type: 'rowPosition';
        panelGeneration: number;
        requestId: number;
        rowNumber: number;
        position: number;
    }
    | {
        /** A short notice for the toast slot (Copy as R code, pins). */
        type: 'notice';
        panelGeneration: number;
        message: string;
        ok: boolean;
    }
    | {
        type: 'error';
        panelGeneration: number;
        message: string;
    }
    | {
        /** Test-only: dispatch a synthetic KeyboardEvent on `window` from
         *  inside the webview, so the integration test harness can drive
         *  the same onKeyDown handler a real keypress would invoke.
         *  Production code paths never post this message; the webview can
         *  only receive messages from its own extension host, so exposing
         *  it does not introduce an external attack surface. */
        type: 'testKey';
        panelGeneration: number;
        key: string;
    }
    | {
        /** Test-only: scroll the grid to a fractional vertical position.
         *  fraction=0 jumps to top, fraction=1 jumps to bottom. The
         *  production UI no longer has Raven-owned scrollbar pointer
         *  handlers; this routes through the grid's imperative scroll API.
         *
         *  Production code paths never post this message; the webview
         *  can only receive messages from its own extension host, so
         *  exposing it does not introduce an external attack surface. */
        type: 'testScrollToFraction';
        panelGeneration: number;
        fraction: number;
    };

export type WebviewToExtension =
    | {
        type: 'webviewReady';
        /** True when the webview tags reader requests with the transform
         *  generation it shows and acks announcements with `adopted`. The
         *  host only waits for adoption from such a webview. */
        adoptsTransforms?: boolean;
    }
    | {
        /** The webview processed the announcement of transform generation
         *  `transformGeneration` (dropped older tiles and switched its
         *  requests to it). Sent on processing, not on the next draw, so a
         *  hidden panel acks too. */
        type: 'adopted';
        panelGeneration: number;
        transformGeneration: number;
    }
    | {
        type: 'lifecycle';
        event: string;
        panelGeneration: number;
        nrow: number;
        columns: number;
        visibleRows: number;
        /** Start row index of the currently rendered window (inclusive).
         *  Used by the test API to verify scroll position. Always reflects
         *  visibleRangeStart at the moment postLifecycle was called. */
        visibleRangeStart: number;
        /** End row index of the currently rendered window (exclusive).
         *  Equal to visibleRangeStart + visibleRows. */
        visibleRangeEnd: number;
        /** Start row index of the rows actually visible within the
         *  viewport (inclusive), excluding overscan rows above or below
         *  the viewport. Used by integration tests that need to prove the
         *  last row is on screen, not merely fetched. */
        viewportRangeStart: number;
        /** End row index of the rows actually visible within the
         *  viewport (exclusive). */
        viewportRangeEnd: number;
        /** Active selection focus cell, or null when no cell is selected. */
        focusCell: { row: number; col: number } | null;
        timestamp: number;
    }
    | {
        type: 'getRows';
        panelGeneration: number;
        requestId: number;
        viewportGeneration: number;
        start: number;
        end: number;
        columns: number[];
        /** Optional half-open range of positions in `columns` needed now
         *  (the horizontally visible ones). When present the host reads
         *  only those columns and each reply row holds `end - start` cells
         *  in `columns` order; the reply echoes the range. Omitted ⇔ all
         *  of `columns`. */
        columnRange?: { start: number; end: number };
        /** Transform generation the webview is showing. */
        transformGeneration?: number;
    }
    | {
        type: 'getLabels';
        panelGeneration: number;
        requestId: number;
        columnIndex: number;
        indices: number[];
    }
    | {
        /** Request the numeric histogram for one column. Sent the first
         *  time a numeric column's filter popover opens and the webview
         *  has no cached bins for it. The host replies with a `histogram`
         *  message. */
        type: 'getHistogram';
        panelGeneration: number;
        requestId: number;
        columnIndex: number;
    }
    | {
        /** The columns the webview wants profiled (on screen in the band,
         *  in the sidebar, or open in value counts), most wanted first,
         *  excluding profiles it already holds. Replaces the previous set;
         *  an empty list stops profiling. */
        type: 'setProfileInterest';
        panelGeneration: number;
        columns: number[];
    }
    | {
        /** Value counts for one column (the frequency popover). */
        type: 'getValueCounts';
        panelGeneration: number;
        requestId: number;
        columnIndex: number;
        order: 'desc' | 'asc';
    }
    | {
        type: 'saveLayout';
        panelGeneration: number;
        /** schemaHash for the dataset the layout was captured against —
         *  used as the store key so a debounced save that lands after a
         *  replace still goes to the right slot. */
        schemaHash: string;
        layout: Layout;
    }
    | {
        type: 'saveToolbar';
        panelGeneration: number;
        schemaHash: string;
        toolbar: ToolbarState;
    }
    | {
        type: 'copy';
        panelGeneration: number;
        requestId: number;
        range: { rowStart: number; rowEnd: number; colIndices: number[] };
        labelsOn: boolean;
        formatOn: boolean;
        digits: number;
        /** When true, prepend a tab-separated row of column names so the
         *  paste lands with headers. Set by the webview for column /
         *  select-all selections. */
        includeHeader: boolean;
        /** "Copy with row names" on a frame without a rowname column:
         *  prepend each row's 1-based R row number. */
        rowNumbers?: boolean;
        /** Transform generation the webview is showing. */
        transformGeneration?: number;
    }
    | {
        /** Fetch one cell's untruncated value (capped at 64 KiB) for the
         *  cell-detail popover. `row` is a display row. */
        type: 'getCellDetail';
        panelGeneration: number;
        requestId: number;
        row: number;
        columnIndex: number;
        /** Transform generation the webview is showing. */
        transformGeneration?: number;
    }
    | {
        /** Write text the webview already has to the clipboard (the
         *  cell-detail popover's Copy button). */
        type: 'copyText';
        panelGeneration: number;
        text: string;
    }
    | {
        /** Apply (or update, or clear) the active sort. The extension
         *  host builds the permutation and broadcasts `sortApplied`.
         *  Sending an empty `keys` array clears the sort. The Labels /
         *  Format / digits snapshot lets the host derive sort keys
         *  WYSIWYG without depending on a separate toolbar-snapshot
         *  message. */
        type: 'setSort';
        panelGeneration: number;
        requestId: number;
        /** Request id of the sort state the webview has actually accepted
         *  and wants restored if this request fails. Older direct callers may
         *  omit it; the host then falls back to its current state. */
        rollbackBaseRequestId?: number;
        keys: SortKey[];
        labelsOn: boolean;
        formatOn: boolean;
        digits: number;
        /** String order for string and label keys. Absent ⇔ `natural`. */
        stringOrder?: StringOrder;
    }
    | {
        /** Debounced persistence of the active sort, mirroring
         *  saveLayout / saveToolbar. The schemaHash echoes the active
         *  one so a save that lands after a replace still goes to the
         *  right slot. */
        type: 'saveSort';
        panelGeneration: number;
        schemaHash: string;
        sort: SortState;
    }
    | {
        /** Apply (or update, or clear) the active filter. The extension
         *  host rebuilds the index and broadcasts `filterApplied`.
         *  Sending an empty `entries` array clears the filter. */
        type: 'setFilters';
        panelGeneration: number;
        requestId: number;
        /** Request id of the filter state the webview has actually accepted
         *  and wants restored if this request fails. Older direct callers may
         *  omit it; the host then falls back to its current state. */
        rollbackBaseRequestId?: number;
        entries: FilterEntry[];
        labelsOn: boolean;
    }
    | {
        type: 'saveFilter';
        panelGeneration: number;
        schemaHash: string;
        filter: FilterState;
    }
    | {
        /** Find in grid: search the displayed text of `columns` (the
         *  visible ones) and reply with the first match at or after
         *  display row `from` (`findResult`). Supersedes any running find;
         *  an empty query cancels. */
        type: 'find';
        panelGeneration: number;
        requestId: number;
        query: string;
        columns: number[];
        labelsOn: boolean;
        formatOn: boolean;
        digits: number;
        from: number;
        /** Transform generation the webview is showing. */
        transformGeneration?: number;
    }
    | {
        /** Next (1) or previous (-1) match of the last find, relative to
         *  display row `from`, wrapping around. */
        type: 'findStep';
        panelGeneration: number;
        requestId: number;
        from: number;
        direction: 1 | -1;
    }
    | {
        /** Stop a running find and forget its matches. */
        type: 'cancelFind';
        panelGeneration: number;
    }
    | {
        /** Go to R row number `rowNumber` (1-based original index). */
        type: 'goToRow';
        panelGeneration: number;
        requestId: number;
        rowNumber: number;
        transformGeneration?: number;
    }
    | {
        /** Copy the current filters, sort and hidden columns as R code
         *  (`r-code.ts`) to the clipboard. */
        type: 'copyAsCode';
        panelGeneration: number;
        requestId: number;
        flavor: 'dplyr' | 'base' | 'data.table';
        hiddenColumns: number[];
    }
    | {
        /** Re-run the `View()` expression in the R console, after the
         *  user confirms. */
        type: 'refresh';
        panelGeneration: number;
    }
    | {
        /** Asks the host to abandon the in-progress restore of a saved
         *  sort/filter (#519) and show the data unsorted/unfiltered,
         *  forgetting the saved preferences. `restoreId` echoes the value
         *  from the `restorePending` being cancelled, so a stale cancel
         *  from a prior lifecycle is ignored by the host. */
        type: 'cancelRestore';
        panelGeneration: number;
        restoreId: number;
    };

/** Hard cap on the number of cells the extension will materialize for a
 *  single copy request. Above this we refuse the copy and surface a
 *  toast in the panel. */
export const COPY_CELL_LIMIT = 5_000_000;
/** Cap on the cell-detail popover's value, in UTF-8 bytes. */
export const CELL_DETAIL_LIMIT_BYTES = 64 * 1024;
